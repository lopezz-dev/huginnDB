/**
 * Column limits on a rule (ADR #113): which columns `insert` may give a value
 * to and `update` may change. Each hangs under its permission's row in the
 * grid — the limit lives beside what it narrows — and both read the columns of
 * the rule's own tables, tagged with what decides whether a pick works:
 * required (no default, no NULL), identity, in how many of the tables.
 *
 * The warnings say what the draft lets through before it is saved, each with
 * the one change that fixes it: a required column missing from `insert`, and
 * `delete` beside a limited `update` — delete-and-re-add would write any column.
 */

import { useTranslation } from "react-i18next";
import { TriangleAlert, Info } from "lucide-react";

import { Button } from "@/components/ui/button";
import { columnAllowed } from "@/lib/policy/glob";
import type { RuleJson } from "@/lib/policy/draft";
import { NamePicker } from "./fields";

/** One column of the rule's tables, folded across them. */
export interface CatalogColumn {
  name: string;
  /** The tables (as `schema.name`) that have it. */
  tables: string[];
  /** The tables where an insert must give it a value: NOT NULL, no default,
   *  not generated. */
  requiredIn: string[];
  /** Generated by the database in every table that has it. */
  identity: boolean;
}

export interface ColumnCatalog {
  /** `null` when there is nothing to read names from — see `reason`. */
  columns: CatalogColumn[] | null;
  /** The tables the columns were read from, as `schema.name`. */
  tables: string[];
  loading: boolean;
  /** Why there are no names to pick from: the rule names no tables, none of
   *  them is on the server, or the server's catalog cannot be read here. */
  reason: "noTables" | "noMatch" | "closed" | null;
}

export type ColumnVerb = "insert" | "update";

/** The rule with one verb's column limit set (`undefined`: every column). */
export function withColumnLimit(
  rule: RuleJson,
  verb: ColumnVerb,
  limit: string[] | undefined,
): RuleJson {
  const columns = { ...(rule.columns ?? {}) };
  if (limit === undefined) delete columns[verb];
  else columns[verb] = limit;
  const next: RuleJson = { ...rule, columns };
  if (Object.keys(columns).length === 0) delete next.columns;
  return next;
}

export function ColumnScopeField({
  verb,
  rule,
  catalog,
  catalogSource,
  closedHint,
  mssql,
  readOnly,
  onChange,
}: {
  verb: ColumnVerb;
  rule: RuleJson;
  catalog: ColumnCatalog;
  catalogSource?: string;
  /** Why the server's catalog cannot be read here — the rule editor's own
   *  hint, so the column pickers say the same as the table pickers. */
  closedHint?: string;
  /** The rule's server is SQL Server, which cannot limit INSERT by column. */
  mssql: boolean;
  readOnly: boolean;
  onChange: (next: RuleJson) => void;
}) {
  const { t } = useTranslation();
  const byName = new Map(
    (catalog.columns ?? []).map((c) => [c.name.toLowerCase(), c]),
  );
  const tableCount = catalog.tables.length;
  return (
    <div className="grid gap-1.5">
      <NamePicker
        label={t(`policyEditor.rule.columns.${verb}`)}
        allLabel={t("policyEditor.rule.columns.all")}
        allExplain={t(`policyEditor.rule.columns.allExplain.${verb}`)}
        emptyLabel={t(`policyEditor.rule.columns.none.${verb}`)}
        emptyIsWarning
        value={rule.columns?.[verb]}
        catalog={catalog.columns?.map((c) => c.name) ?? null}
        catalogLoading={catalog.loading}
        catalogSource={catalogSource}
        noCatalogHint={
          catalog.reason === "noTables"
            ? t("policyEditor.rule.columns.noTables")
            : catalog.reason === "noMatch"
              ? t("policyEditor.rule.columns.noMatch", { source: catalogSource ?? "" })
              : closedHint
        }
        describe={(name) => {
          const c = byName.get(name.toLowerCase());
          if (!c) return {};
          if (c.identity) {
            return { tag: t("policyEditor.rule.columns.identity"), disabled: true };
          }
          const where =
            tableCount > 1 && c.tables.length < tableCount
              ? c.tables.join(", ")
              : tableCount > 1
                ? t("policyEditor.rule.columns.inAll", { count: tableCount })
                : "";
          const required =
            verb === "insert" && c.requiredIn.length > 0
              ? t("policyEditor.rule.columns.required")
              : "";
          return {
            tag: [where, required].filter(Boolean).join(" · ") || undefined,
            warn: !!required,
          };
        }}
        readOnly={readOnly}
        onChange={(limit) => onChange(withColumnLimit(rule, verb, limit))}
      />
      {verb === "insert" && mssql && rule.columns?.insert !== undefined && (
        <p className="flex items-start gap-1.5 text-3xs text-muted-foreground">
          <Info aria-hidden className="mt-px h-3 w-3 shrink-0" />
          {t("policyEditor.rule.columns.mssqlInsert")}
        </p>
      )}
    </div>
  );
}

/** One thing the draft lets through, and the change that closes it. */
interface ColumnWarning {
  key: string;
  title: string;
  body: string;
  fixLabel: string;
  fix: () => void;
}

export function ColumnWarnings({
  rule,
  catalog,
  readOnly,
  onChange,
}: {
  rule: RuleJson;
  catalog: ColumnCatalog;
  readOnly: boolean;
  onChange: (next: RuleJson) => void;
}) {
  const { t } = useTranslation();
  const human = rule.human ?? [];
  const warnings: ColumnWarning[] = [];

  // A required column outside the insert list: every new row would fail.
  const insertLimit = rule.columns?.insert;
  if (human.includes("insert") && insertLimit !== undefined) {
    const missing = new Map<string, string[]>();
    for (const c of catalog.columns ?? []) {
      if (c.identity || columnAllowed(insertLimit, c.name)) continue;
      for (const table of c.requiredIn) {
        missing.set(table, [...(missing.get(table) ?? []), c.name]);
      }
    }
    for (const [table, names] of missing) {
      warnings.push({
        key: `required:${table}`,
        title: t("policyEditor.rule.columns.warnRequiredTitle", { table }),
        body: t("policyEditor.rule.columns.warnRequiredBody", {
          columns: names.join(", "),
          count: names.length,
        }),
        fixLabel: t("policyEditor.rule.columns.warnRequiredFix", {
          columns: names.join(", "),
        }),
        fix: () =>
          onChange(
            withColumnLimit(rule, "insert", [
              ...insertLimit,
              ...names.filter((n) => !columnAllowed(insertLimit, n)),
            ]),
          ),
      });
    }
  }

  // Delete and re-add writes any column the update limit protects.
  if (
    human.includes("delete") &&
    human.includes("insert") &&
    rule.columns?.update !== undefined
  ) {
    warnings.push({
      key: "recreate",
      title: t("policyEditor.rule.columns.warnRecreateTitle"),
      body:
        insertLimit === undefined
          ? t("policyEditor.rule.columns.warnRecreateBodyAll")
          : t("policyEditor.rule.columns.warnRecreateBody", {
              columns: insertLimit.join(", "),
            }),
      fixLabel: t("policyEditor.rule.columns.warnRecreateFix"),
      fix: () =>
        onChange({
          ...rule,
          human: human.filter((p) => p !== "delete"),
          ai: (rule.ai ?? []).filter((p) => p !== "delete"),
        }),
    });
  }

  if (warnings.length === 0) return null;
  return (
    <div className="grid gap-2">
      {warnings.map((w) => (
        <div
          key={w.key}
          role="note"
          className="flex items-start gap-2 rounded-md border border-warning/40 bg-warning/5 px-3 py-2"
        >
          <TriangleAlert aria-hidden className="mt-0.5 h-3.5 w-3.5 shrink-0 text-warning" />
          <div className="grid min-w-0 gap-1">
            <p className="text-xs font-medium text-warning">{w.title}</p>
            <p className="text-2xs text-muted-foreground">{w.body}</p>
            {!readOnly && (
              <div>
                <Button size="xs" variant="outline" onClick={w.fix}>
                  {w.fixLabel}
                </Button>
              </div>
            )}
          </div>
        </div>
      ))}
    </div>
  );
}
